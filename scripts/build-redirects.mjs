#!/usr/bin/env node
/**
 * build-redirects.mjs — generate host redirect config from lib/redirects.ts.
 *
 * A static export cannot serve 301s itself, and the chamber's existing hosting
 * is Apache/PHP, so all three common formats are written and the README says
 * which one to keep. Runs as part of `npm run build`.
 */

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");

// Parsed out of the TS file so the list lives in exactly one place.
const src = await readFile(join(ROOT, "lib", "redirects.ts"), "utf8");
const block = src.slice(src.indexOf("REDIRECTS"), src.indexOf("/** Routes for the sitemap"));
const pairs = [...block.matchAll(/\{\s*from:\s*"([^"]+)",\s*to:\s*"([^"]+)"\s*\}/g)].map(
  (m) => ({ from: m[1], to: m[2] }),
);

if (pairs.length === 0) {
  console.error("No redirects parsed from lib/redirects.ts — check the file format.");
  process.exit(1);
}

await mkdir(PUBLIC, { recursive: true });

/* ------------------------------------------------------------ Apache */
const htaccess = `# Generated by scripts/build-redirects.mjs — do not edit by hand.
# Redirects from the old PHP site. Edit lib/redirects.ts and rebuild.

Options -MultiViews
RewriteEngine On

# Serve pre-compressed assets and set long cache lives on hashed output.
<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript image/svg+xml
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/avif "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType text/html "access plus 1 hour"
</IfModule>

# --- Old URLs -------------------------------------------------------------
${pairs
  .map((p) => {
    // Escape regex metacharacters; keep the query-string forms working.
    const from = p.from.replace(/^\//, "").replace(/[.?&]/g, (c) => "\\" + c);
    return `RewriteRule ^${from}$ ${p.to} [R=301,L,NE]`;
  })
  .join("\n")}

# --- Trailing slashes ----------------------------------------------------
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^(.*[^/])$ /$1/ [R=301,L]

ErrorDocument 404 /404.html
`;

/* ---------------------------------------------- Netlify / Cloudflare */
const netlify = `# Generated by scripts/build-redirects.mjs — do not edit by hand.
${pairs.map((p) => `${p.from}  ${p.to}  301`).join("\n")}
`;

/* ------------------------------------------------------------ Vercel */
const vercel = JSON.stringify(
  {
    $schema: "https://openapi.vercel.sh/vercel.json",
    redirects: pairs.map((p) => ({ source: p.from, destination: p.to, permanent: true })),
  },
  null,
  2,
);

await writeFile(join(PUBLIC, ".htaccess"), htaccess);
await writeFile(join(PUBLIC, "_redirects"), netlify);
await writeFile(join(PUBLIC, "vercel.json"), vercel);

console.log(
  `Wrote ${pairs.length} redirects to public/.htaccess, public/_redirects and public/vercel.json`,
);
